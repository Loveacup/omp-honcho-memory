#!/usr/bin/env python3
"""Durable verification carrier for S2a (pure raw-recall formatting).

This carrier proves the *behaviour* of ``formatRawRecall`` from
``extensions/raw-recall.ts`` — not just its source text — hermetically:

  * No network at all. The formatter is a pure function; the harness only
    constructs synthetic ``RawSearchResult`` objects in memory and asserts on
    the returned string. ``HONCHO_*`` env vars are stripped from the subprocess
    as belt-and-suspenders even though the formatter reads neither env nor
    config nor clock.
  * No real credentials / config are ever read (the formatter has no such code
    path); the synthetic inputs contain only fake, non-secret values.
  * The temporary Bun harness scripts are written to a scratch dir and removed
    afterwards; the product source is never rewritten on disk (the mutation
    negative-control patches it in-memory via a Bun ``onLoad`` plugin).

Harnesses generated at run time:

  main      -- imports extensions/raw-recall.ts and exercises the formatter:
               happy path + field/provenance preservation, metadata is never
               dumped, the fixed safety notice, all transport statuses,
               transport partial/conflict passthrough, input non-mutation,
               <>& / hostile-closing-tag escaping (single always-valid JSON
               object), Unicode surrogate-safe truncation, over-long content
               truncation, budget omission of whole entries, an extremely small
               budget returning an explicit ``budget_exceeded`` marker with no
               leaked evidence, input order preservation (no "latest == current"
               inference), and an exact ``length <= budget`` sweep. If the module
               is absent the import is caught and reported as a genuine failing
               assertion (the RED baseline), not a skip.

  mutate    -- re-runs the main harness but uses a Bun ``onLoad`` plugin to
               disable the ``<`` escape in-memory. This MUST turn the escaping
               assertion RED, proving that assertion actually bites. The control
               passes only when the mutated run fails with that specific FAIL.

Exit code is non-zero if any executed harness reports a failing assertion, or if
the negative control does not go RED as expected.
"""

from __future__ import annotations

