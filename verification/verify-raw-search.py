def _render(tpl: str, **kw: str) -> str:
    # Templates use doubled braces for literal JS braces; single-brace {NAME}
    # tokens are our substitutions. str.format handles both.
    return tpl.format(**kw)


def run_harness(name: str, source: str, workdir: Path, bun: str) -> tuple[int, str]:
    path = workdir / f"harness-{name}.ts"
    path.write_text(GUARD + source, encoding="utf-8")
    env = dict(os.environ)
    # Credential isolation is done INSIDE the harness (routing mocks ./config.js
    # before importing tools.ts; edge imports raw-search.ts, which reads no
    # config at all). We therefore do NOT reassign HOME/USERPROFILE — the real
    # ~/.honcho/config.json is never consulted regardless of HOME. We still strip
    # any HONCHO_* env so a stray real value can never influence a harness even
    # if a future code path fell back to process.env.
    for key in [
        "HONCHO_API_KEY",
        "HONCHO_WORKSPACE",
        "HONCHO_PEER_NAME",
        "HONCHO_USERNAME",
        "HONCHO_AI_PEER",
        "HONCHO_URL",
    ]:
        env.pop(key, None)
    proc = subprocess.run(
        [bun, str(path)],
        cwd=str(REPO),
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )
    out = (
        f"$ bun harness-{name} (cwd={REPO})\n"
        f"--- stdout ---\n{proc.stdout}\n"
        f"--- stderr ---\n{proc.stderr}\n"
        f"--- exit: {proc.returncode} ---\n"
    )
    return proc.returncode, out


def main() -> int:
    bun = _bun()
    workdir = Path(tempfile.mkdtemp(prefix="raw-search-verify-"))
    overall = 0
    report: list[str] = []
    try:
        # Routing harness always runs (imports only tools.ts).
        routing_src = _render(
            ROUTING_HARNESS,
            TOOLS_IMPORT=str(TOOLS),
            CONFIG_IMPORT=str(CONFIG),
            OFFICIAL_ORIGIN=OFFICIAL_ORIGIN,
            EXPECTED_PATH=EXPECTED_PATH,
            FAKE_API_KEY=FAKE_API_KEY,
            FAKE_PEER=FAKE_PEER,
            FAKE_WORKSPACE=FAKE_WORKSPACE,
            FAKE_AI_PEER_PLACEHOLDER=FAKE_AI_PEER,
        )
        rc, out = run_harness("routing", routing_src, workdir, bun)
        report.append(out)
        overall = overall or rc

        # Edge harness runs only when raw-search.ts exists (skipped cleanly in RED).
        if RAW_SEARCH.exists():
            edge_src = _render(
                EDGE_HARNESS,
                RAW_SEARCH_IMPORT=str(RAW_SEARCH),
                FAKE_API_KEY=FAKE_API_KEY,
                FAKE_PEER=FAKE_PEER,
                FAKE_WORKSPACE=FAKE_WORKSPACE,
                EXPECTED_PATH=EXPECTED_PATH,
            )
            rc, out = run_harness("edge", edge_src, workdir, bun)
            report.append(out)
            overall = overall or rc

            # Real product mutation via Bun onLoad: no shared source rewrite.
            mutation = r'''
import { plugin } from "bun";
await plugin({ name: "delete-mutation", setup(build) {
  build.onLoad({ filter: /raw-search\.ts$/ }, async ({ path }) => {
    const source = await Bun.file(path).text();
    const needle = 'method: "POST"';
    if (source.split(needle).length !== 2) throw new Error("mutation anchor mismatch");
    console.log("MUTATION_APPLIED POST -> DELETE");
    return { contents: source.replace(needle, 'method: "DELETE"'), loader: "ts" };
  });
} });
'''
            # Use the invalid-JSON case where DELETE otherwise still returns the
            # expected product error: only the external guard makes it RED.
            delete_src = edge_src.split("// ---- non-array JSON ----", 1)[0]
            delete_src += '\nconsole.log("DELETE_SUMMARY failures=" + failures);\nprocess.exit(failures ? 1 : 0);\n'
            rc, out = run_harness("delete-mutation", mutation + delete_src, workdir, bun)
            report.append(out)
            red = (rc == 1 and "MUTATION_APPLIED" in out
                   and "FAIL GLOBAL_GUARD method must be POST" in out
                   and "PASS invalid JSON -> error" in out and "DELETE_SUMMARY failures=1" in out)
            report.append(f"DELETE_MUTATION_EXPECTED_RED={'PASS' if red else 'FAIL'} actual_exit={rc}")
            overall = overall or (0 if red else 1)

            # These attempts are caught like product failures; the guard counter
            # must still make the harness RED (including config write attempts).
            probes = r'''
for (const attempt of [
  () => guardFetch(async () => ({}), "q")("https://evil.example/v3/workspaces/oh%2Fmy%20pi/search", { method: "POST", body: '{"query":"q","limit":10}' }),
  () => guardFetch(async () => ({}), "q")("https://api.honcho.dev/v3/workspaces/oh/my%20pi/search", { method: "POST", body: '{"query":"q","limit":10}' }),
  () => guardFetch(async () => ({}), "q")("https://api.honcho.dev/v3/workspaces/oh%2Fmy%20pi/search", { method: "POST", body: '{"query":"q","limit":10,"filters":{}}' }),
  () => configProbe.saveConfig({}),
  () => configProbe.saveRootField("probe", true),
]) { try { await attempt(); } catch {} }
'''
            probe_src = routing_src.replace(
                'console.log("ROUTING_SUMMARY',
                f'const configProbe = await import("{CONFIG}");\n' + probes + '\nconsole.log("ROUTING_SUMMARY',
            )
            rc, out = run_harness("guard-probes", probe_src, workdir, bun)
            report.append(out)
            red = rc != 0 and out.count("FAIL GLOBAL_GUARD") == 5
            report.append(f"GUARD_PROBES_EXPECTED_RED={'PASS' if red else 'FAIL'} actual_exit={rc}")
            overall = overall or (0 if red else 1)
        else:
            report.append(
                "$ edge harness SKIPPED :: extensions/raw-search.ts absent "
                "(expected during RED against original behaviour)\n"
            )
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    print("\n".join(report))
    if overall == 0:
        print("VERIFY-RAW-SEARCH: GREEN (normal assertions passed; negative controls correctly RED)")
    else:
        print("VERIFY-RAW-SEARCH: FAIL (see failing assertions above)")
    return overall


