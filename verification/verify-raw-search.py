#!/usr/bin/env python3
"""Durable verification carrier for Slice 1 (raw workspace search).

This carrier proves the *behaviour* of the registered ``honcho_search`` tool
callback and of the ``searchWorkspaceMessages`` transport, not just their source
text. It does so hermetically:

  * No real Honcho requests. ``globalThis.fetch`` is mocked in the routing
    harness and an in-memory ``fetchImpl`` is injected in the edge harness.
  * No real credentials / config. Instead of reassigning ``HOME``, the routing
    harness mocks the ``./config.js`` module (via ``bun:test`` ``mock.module``)
    with a fake ``resolveConfig`` *before* dynamically importing ``tools.ts``, so
    the real ``~/.honcho/config.json`` is never read. The edge harness imports
    ``raw-search.ts`` directly, which reads no config at all. All ``HONCHO_*``
    env vars are stripped from the subprocess as belt-and-suspenders.
  * The temporary Bun harness scripts are written to a scratch dir and removed
    afterwards; source mutations are in-memory only.

Two Bun harnesses are generated at run time:

  routing  -- imports extensions/tools.ts, registers the tools with a mock
              ExtensionAPI + spied deps.getHandles, and drives the *registered*
              honcho_search.execute callback through a mocked global fetch.
              This is the RED/GREEN pivot: the original implementation calls
              handles.session.search (no workspace POST), the new one issues a
              single POST /v3/workspaces/{encoded}/search with body
              {query, limit:10} and never touches getHandles/session.search.

  edge     -- imports extensions/raw-search.ts directly and exercises the
              transport edge cases with an injected fetchImpl: 3500ms default
              budget (incl. body read), timeout, cancellation, non-200, invalid
              JSON, non-array, mixed workspace, missing provenance, exact
              dedupe, id/content conflict, unsupported origin, redirect:error,
              field preservation + retrievedAt, and no-fallback for target=user.
              Skipped (not failed) when raw-search.ts is absent so the RED run
              produces a clean behavioural failure rather than an import error.

Exit code is non-zero if any executed harness reports a failing assertion.
"""

